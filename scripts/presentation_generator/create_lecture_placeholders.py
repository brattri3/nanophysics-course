def format_text_placeholder(shape, title, bullets):
    tf = shape.TextFrame
    tf.WordWrap = -1  # msoTrue
    
    # Build text lines
    lines = [title] + bullets
    full_text = "\r".join(lines)
    
    tf.TextRange.Text = full_text
    
    # Format each paragraph
    count = tf.TextRange.Paragraphs().Count
    for i in range(1, count + 1):
        p = tf.TextRange.Paragraphs(i)
        txt = p.Text.strip()
        if i == 1:
            p.Font.Name = "Arial"
            p.Font.Size = 15
            p.Font.Bold = -1
            p.Font.Color.RGB = 6237184  # GUAP blue (0x5F2C00)
            p.ParagraphFormat.SpaceBefore = 3
            p.ParagraphFormat.SpaceAfter = 5
            p.ParagraphFormat.Bullet.Type = 0
        else:
            p.Font.Name = "Arial"
            p.Font.Size = 12
            p.Font.Bold = 0
            p.Font.Color.RGB = 3418148  # Dark text (0x342824)
            p.ParagraphFormat.SpaceBefore = 1.5
            p.ParagraphFormat.SpaceAfter = 1.5
            p.ParagraphFormat.Bullet.Type = 0

